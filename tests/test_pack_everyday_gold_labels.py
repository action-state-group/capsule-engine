"""Gold labels for the everyday pack's fixture corpus: what each row's
expected outcome was established under, captured when the scenarios run.

Run ``python -m tests.test_pack_everyday_gold_labels`` to rewrite
``fixtures/gold_labels.yaml`` after regenerating the fixture ledger.

Each row carries three orthogonal labels, never folded into one another:

- population (declared per n/a constraint in ``decision_table.yaml``):
  ``a`` the rule applied and a named field was missing ("correct decline"),
  ``b`` the record does not say why the rule did not settle ("recording
  defect"), ``c`` the rule did not apply (never scored);
- ``evaluator_tier``: ``recomputed`` (a deterministic predicate produced it)
  or ``judged`` (a model produced it) -- named so it cannot be confused with
  an obligation's gating tier;
- ``judge_pin_digest``: required on a judged row, forbidden on a recomputed
  row.

and two identities: ``config_identity`` (the pack and the digest of every
wicket that ran) and ``code_identity`` (below).

``code_identity`` is a LOCAL, INTERIM field, pending a field in the Agent
Action Capsule evidence-result schema [recomputed-tier-code-identity]. When
that field lands, this one is renamed onto it, never kept beside it. It is
``{kind, value, assurance}``: ``kind`` is ``source_tree_sha256`` (SHA-256
over the sorted ``"<path>\\0<sha256 of file>\\n"`` lines of the
verdict-producing source, see ``CODE_SCOPE``) or ``git_commit``; ``value`` is
the digest or commit, or ``"unknown"`` when it could not be resolved at
check time; ``assurance`` is a level from the existing ladder (self-attested
| witnessed | countersigned). Its limit: a code identity is a claim made by
whoever built the artifact (self-attested). It makes rows COMPARABLE -- the
same code across a window -- not CHECKABLE: a stranger cannot confirm it
from the receipt.

A recomputed row whose code identity is missing or ``"unknown"`` cannot be
reproduced, so it is classified population ``b`` -- never relabelled
``judged``. Population ``b`` is a regression detector: zero in a conforming
build; nonzero means the n/a invariant was bypassed or a foreign producer
wrote the record. It is counted on its own and never enters a rate.
"""
