REPO = Path(__file__).parent.parent
PACK_DIR = REPO / "capsule_engine" / "packs" / "catalog" / "everyday"
GOLD_PATH = PACK_DIR / "fixtures" / "gold_labels.yaml"
LEDGER_PATH = PACK_DIR / "fixtures" / "mini_ledger.jsonl"

# The source that produces a guard verdict: the checks and engine, the fold
# engine caps reads, and the pack/manifest path that configures them.
CODE_SCOPE = ("capsule_engine/guards", "capsule_engine/folds", "capsule_engine/policy", "capsule_engine/packs")
EVALUATOR_TIERS = frozenset({"recomputed", "judged"})
ASSURANCE_LEVELS = frozenset({"self-attested", "witnessed", "countersigned"})
CODE_IDENTITY_KINDS = frozenset({"source_tree_sha256", "git_commit"})
_HEX64 = re.compile(r"^[0-9a-f]{64}$")
_HEX40 = re.compile(r"^[0-9a-f]{40}$")

HEADER = """\
# Gold labels for the everyday fixture corpus. GENERATED by
# `python -m tests.test_pack_everyday_gold_labels` from the scenario run that
# produced mini_ledger.jsonl -- except the row marked hand_authored, which is
# a deliberate constant and must never be replaced by engine output.
# Population per n/a constraint is declared in decision_table.yaml.
#
# code_identity: a local, interim field, pending a field in the Agent Action
# Capsule evidence-result schema [recomputed-tier-code-identity]; renamed onto
# that field when it lands, never kept beside it. A code identity is a claim
# by whoever built the artifact (self-attested): it makes rows comparable
# across a window, not checkable by a stranger from the receipt.
"""

