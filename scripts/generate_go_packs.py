"""Write, or check, the Go module's embedded pack tree from this repo's catalog.

The Go guard (``go/``) embeds its packs, and Go ``embed`` cannot read outside
the module directory, so ``go/packs/`` holds a copy of each pack version the
Go guard serves. This script is the only thing that writes it. Its sources are
this repository's own:

* ``python/capsule_engine/packs/catalog/<pack>/pack.yaml`` (the current version);
* ``python/capsule_engine/guards/wickets/catalog_defs/`` and
  ``python/capsule_engine/folds/catalog_defs/`` (every definition version);
* ``python/capsule_engine/guards/action_taxonomy.json``.

A pack version directory, once written, is frozen: its pack.yaml and
PROVENANCE.json are never rewritten, so an older pinned pack keeps loading at
its digest. Only the current version of a served pack is written, and only
when its directory is missing. It holds the pack.yaml, the definitions it
cites, and the definitions the previous version's directory held (so a
pack.yaml-only source citing them still resolves, as before).

Generated Go: ``go/packs/embed.go`` (one ``embed.FS`` per version, ``All``
over the whole tree, and ``ActionTaxonomy``) and ``go/pack/registry_gen.go``
(a ``Load<Version>`` function per version and the vendored list). Generated
test data: ``go/guard/testdata/engine-definitions.json``, every catalog
definition's digest, the retired pairs and each served pack's current
version, which the Go guard's tests hold its ported definitions against.

``--check`` writes nothing and fails on any difference:

* the current version of each served pack is present, with the catalog's
  pack.yaml byte for byte;
* every definition file under ``go/packs`` equals its namesake in catalog_defs;
* every PROVENANCE.json's ``engine_definition_digest`` equals what this
  engine computes for that directory today, and each listed file's sha256
  holds;
* ``engine/action_taxonomy.json`` and its PROVENANCE.json are what this script
  writes from the engine's taxonomy;
* the two generated Go files are what this script writes.

Usage::

    python scripts/generate_go_packs.py           # write
    python scripts/generate_go_packs.py --check   # CI
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
import tempfile
from pathlib import Path

import yaml

from capsule_engine.folds.loader import load_definition_file as load_fold_file
from capsule_engine.guards.classes import TAXONOMY_DIGEST, TAXONOMY_VERSION
from capsule_engine.guards.wickets.loader import load_definition_file as load_wicket_file
from capsule_engine.guards.wickets.retired import RETIRED
from capsule_engine.packs.loader import load_pack_dir

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "python" / "capsule_engine" / "packs" / "catalog"
WICKET_DEFS = ROOT / "python" / "capsule_engine" / "guards" / "wickets" / "catalog_defs"
FOLD_DEFS = ROOT / "python" / "capsule_engine" / "folds" / "catalog_defs"
TAXONOMY = ROOT / "python" / "capsule_engine" / "guards" / "action_taxonomy.json"
GO = ROOT / "go"
PACKS = GO / "packs"
EMBED_GO = PACKS / "embed.go"
REGISTRY_GO = GO / "pack" / "registry_gen.go"
DEFINITIONS_JSON = GO / "guard" / "testdata" / "engine-definitions.json"

# The packs the Go guard serves. Another catalog pack is not embedded.
SERVED = ("everyday", "seller")

VERSION_DIR = re.compile(r"^(?P<name>[a-z]+)-(?P<version>\d+\.\d+\.\d+)$")
HEADER = "// Code generated by scripts/generate_go_packs.py; DO NOT EDIT.\n"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _version_key(version: str) -> tuple[int, ...]:
    return tuple(int(part) for part in version.split("."))


def _go_name(dir_name: str) -> str:
    m = VERSION_DIR.match(dir_name)
    assert m, dir_name
    return m["name"].capitalize() + m["version"].replace(".", "")


def _version_dirs() -> list[Path]:
    return sorted(
        (d for d in PACKS.iterdir() if d.is_dir() and VERSION_DIR.match(d.name)),
        key=lambda d: (VERSION_DIR.match(d.name)["name"], _version_key(VERSION_DIR.match(d.name)["version"])),
    )


def _definitions(directory: Path, load, id_attr: str) -> dict[str, tuple[Path, str]]:
    """Every definition in a catalog_defs directory, by its id: (file, digest)."""
    out: dict[str, tuple[Path, str]] = {}
    for path in sorted(directory.glob("*.yaml")):
        definition = load(path)
        out[getattr(definition, id_attr)] = (path, definition.definition_digest())
    return out


def pack_digest(directory: Path) -> str:
    """The engine's definition digest of a pack directory. A pack.yaml naming a
    bootstrap file that is not vendored loads with an empty stand-in: the
    bootstrap's bytes are not inside the digest."""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / directory.name
        shutil.copytree(directory, copy)
        bootstrap = (yaml.safe_load((copy / "pack.yaml").read_text()) or {}).get("bootstrap")
        if bootstrap and not (copy / bootstrap).exists():
            (copy / bootstrap).write_text("")
        return load_pack_dir(copy).definition_digest()


def _cited(pack_yaml: Path) -> tuple[list[str], list[str]]:
    data = yaml.safe_load(pack_yaml.read_text()) or {}
    wickets = [c["wicket_ref"] for c in data.get("constraints") or [] if isinstance(c, dict) and "wicket_ref" in c]
    folds = [f["fold_ref"] for f in data.get("folds") or [] if isinstance(f, dict) and "fold_ref" in f]
    return wickets, folds


def _new_version_dir(name: str, problems: list[str], write: bool) -> None:
    """Write the current version of a served pack when its directory is missing."""
    source = CATALOG / name / "pack.yaml"
    pack = load_pack_dir(CATALOG / name)
    version = pack.pack_id.rsplit("/", 1)[1]
    target = PACKS / f"{name}-{version}"
    if target.exists():
        if (target / "pack.yaml").read_bytes() != source.read_bytes():
            problems.append(f"{target.name}/pack.yaml is not the catalog's {name} pack.yaml")
        return
    if not write:
        problems.append(f"{target.name} is missing: the catalog's {name} pack is {pack.pack_id}")
        return
    wicket_defs = _definitions(WICKET_DEFS, load_wicket_file, "wicket_id")
    fold_defs = _definitions(FOLD_DEFS, load_fold_file, "fold_id")
    cited_wickets, cited_folds = _cited(source)
    files: dict[str, Path] = {}
    for wid in cited_wickets:
        files[f"wickets/{wicket_defs[wid][0].name}"] = wicket_defs[wid][0]
    for fid in cited_folds:
        files[f"folds/{fold_defs[fid][0].name}"] = fold_defs[fid][0]
    previous = [d for d in _version_dirs() if VERSION_DIR.match(d.name)["name"] == name]
    catalog_only: dict[str, dict[str, str]] = {"wicket_digests": {}, "fold_digests": {}}
    if previous:
        for sub, defs_dir, load, kind in (
            ("wickets", WICKET_DEFS, load_wicket_file, "wicket_digests"),
            ("folds", FOLD_DEFS, load_fold_file, "fold_digests"),
        ):
            for held in sorted((previous[-1] / sub).glob("*.yaml")):
                key = f"{sub}/{held.name}"
                if key not in files:
                    files[key] = defs_dir / held.name
                    definition = load(defs_dir / held.name)
                    ident = getattr(definition, "wicket_id" if sub == "wickets" else "fold_id")
                    catalog_only[kind][ident] = definition.definition_digest()
    target.mkdir(parents=True)
    shutil.copyfile(source, target / "pack.yaml")
    for rel, src in sorted(files.items()):
        (target / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, target / rel)
    provenance = {
        "note": "Generated by scripts/generate_go_packs.py from this repository's catalog; it is not part of the pack's bytes.",
        "pack_id": pack.pack_id,
        "source": "python/capsule_engine/packs/catalog/" + name,
        "engine_definition_digest": pack_digest(target),
        "wicket_digests": {wid: wicket_defs[wid][1] for wid in cited_wickets},
        "fold_digests": {fid: fold_defs[fid][1] for fid in cited_folds},
        "catalog_only": catalog_only,
        "files": {
            rel: {"source_path": str(src.relative_to(ROOT)), "sha256": _sha256(target / rel)}
            for rel, src in sorted(files.items())
        },
    }
    (target / "PROVENANCE.json").write_text(json.dumps(provenance, indent=2) + "\n")


def _check_tree(problems: list[str]) -> None:
    for directory in _version_dirs():
        for sub, defs_dir in (("wickets", WICKET_DEFS), ("folds", FOLD_DEFS)):
            for held in sorted((directory / sub).glob("*")):
                source = defs_dir / held.name
                if not source.is_file() or source.read_bytes() != held.read_bytes():
                    problems.append(f"{directory.name}/{sub}/{held.name} is not {source.relative_to(ROOT)}")
        provenance = json.loads((directory / "PROVENANCE.json").read_text())
        digest = pack_digest(directory)
        if provenance.get("engine_definition_digest") != digest:
            problems.append(
                f"{directory.name}: PROVENANCE digest {provenance.get('engine_definition_digest')} is not the engine's {digest}"
            )
        for rel, entry in (provenance.get("files") or {}).items():
            path = directory / rel
            if not path.is_file() or _sha256(path) != entry.get("sha256"):
                problems.append(f"{directory.name}/{rel}: sha256 is not the one PROVENANCE.json records")


def render_taxonomy_provenance() -> str:
    data = {
        "note": "Generated by scripts/generate_go_packs.py; it is not part of the taxonomy's bytes.",
        "files": {
            "action_taxonomy.json": {
                "source_path": str(TAXONOMY.relative_to(ROOT)),
                "sha256": _sha256(TAXONOMY),
            }
        },
        "used_for": "the action-class table (guards/classes.py reads it): approver_role per class, which decides escalate vs deny on a caps failure, and legacy_aliases, through which a caps_minor key resolves to its canonical class",
        "taxonomy_version": TAXONOMY_VERSION,
        "jcs_digest": TAXONOMY_DIGEST,
    }
    return json.dumps(data, indent=2) + "\n"


def render_embed() -> str:
    lines = [
        HEADER,
        "// Package packs embeds the pack versions the Go guard serves, copied from",
        "// capsule-engine's catalog by scripts/generate_go_packs.py. Each version",
        "// directory carries a PROVENANCE.json sidecar with its engine definition",
        "// digest; the sidecar is not part of the pack's bytes.",
        "package packs",
        "",
        'import "embed"',
        "",
        "// All is the whole pack tree: every version directory and engine/.",
        "//",
        "//go:embed engine " + " ".join(d.name for d in _version_dirs()),
        "var All embed.FS",
    ]
    for directory in _version_dirs():
        name = _go_name(directory.name)
        pack_id = json.loads((directory / "PROVENANCE.json").read_text())["pack_id"]
        lines += [
            "",
            f"// {name} is {pack_id}: its pack.yaml, the definitions it cites, and",
            "// PROVENANCE.json.",
            "//",
            f"//go:embed {directory.name}",
            f"var {name} embed.FS",
            "",
            f"// {name}Dir is the directory of {pack_id} inside {name}.",
            f'const {name}Dir = "{directory.name}"',
        ]
    lines += [
        "",
        "// ActionTaxonomy is capsule-engine's action-class table",
        "// (guards/action_taxonomy.json): each class's approver_role and legacy",
        "// aliases.",
        "//",
        "//go:embed engine/action_taxonomy.json",
        "var ActionTaxonomy []byte",
        "",
    ]
    return "\n".join(lines)


def render_registry() -> str:
    dirs = _version_dirs()
    lines = [
        HEADER,
        "package pack",
        "",
        "import (",
        '\t"io/fs"',
        "",
        '\t"github.com/action-state-group/capsule-engine/go/packs"',
        ")",
    ]
    for directory in dirs:
        name = _go_name(directory.name)
        pack_id = json.loads((directory / "PROVENANCE.json").read_text())["pack_id"]
        lines += [
            "",
            f"// Load{name} loads {pack_id}, at the digest its PROVENANCE.json records.",
            f"func Load{name}() (Pack, error) {{",
            f"\treturn LoadFrom(packs.{name}, packs.{name}Dir)",
            "}",
        ]
    lines += [
        "",
        "// EmbeddedPack is one embedded pack version: its directory in packs.All",
        "// and its loader.",
        "type EmbeddedPack struct {",
        "\tDir  string",
        "\tLoad func() (Pack, error)",
        "}",
        "",
        "// Embedded is every embedded pack version, oldest first by pack.",
        "func Embedded() []EmbeddedPack {",
        "\treturn []EmbeddedPack{",
    ]
    for directory in dirs:
        name = _go_name(directory.name)
        lines.append(f"\t\t{{packs.{name}Dir, Load{name}}},")
    lines += [
        "\t}",
        "}",
        "",
        "// vendored are the embedded packs, each with its PROVENANCE.json sidecar.",
        "var vendored = []struct {",
        "\tfsys fs.FS",
        "\tdir  string",
        "}{",
    ]
    for directory in dirs:
        name = _go_name(directory.name)
        lines.append(f"\t{{packs.{name}, packs.{name}Dir}},")
    lines += ["}", ""]
    return "\n".join(lines)


def render_definitions() -> str:
    current = {name: f"{name}-{load_pack_dir(CATALOG / name).pack_id.rsplit('/', 1)[1]}" for name in SERVED}
    data = {
        "note": "Generated by scripts/generate_go_packs.py; do not edit. The engine's digest of every catalog definition, the retired pairs, and the current version of each pack the Go guard serves.",
        "wickets": {wid: digest for wid, (_, digest) in sorted(_definitions(WICKET_DEFS, load_wicket_file, "wicket_id").items())},
        "folds": {fid: digest for fid, (_, digest) in sorted(_definitions(FOLD_DEFS, load_fold_file, "fold_id").items())},
        "retired": {r.wicket_id: r.digest for r in RETIRED},
        "current": current,
    }
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="write nothing; fail on any difference")
    args = parser.parse_args(argv)
    problems: list[str] = []
    for name in SERVED:
        _new_version_dir(name, problems, write=not args.check)
    _check_tree(problems)
    if not args.check:
        (PACKS / "engine").mkdir(parents=True, exist_ok=True)
        shutil.copyfile(TAXONOMY, PACKS / "engine" / "action_taxonomy.json")
    elif not (PACKS / "engine" / "action_taxonomy.json").is_file() or (
        (PACKS / "engine" / "action_taxonomy.json").read_bytes() != TAXONOMY.read_bytes()
    ):
        problems.append("engine/action_taxonomy.json is not python/capsule_engine/guards/action_taxonomy.json")
    for path, text in (
        (EMBED_GO, render_embed()),
        (REGISTRY_GO, render_registry()),
        (DEFINITIONS_JSON, render_definitions()),
        (PACKS / "engine" / "PROVENANCE.json", render_taxonomy_provenance()),
    ):
        if args.check:
            if not path.is_file() or path.read_text() != text:
                problems.append(f"{path.relative_to(GO.parent)} is not what this script writes")
        else:
            path.write_text(text)
    for problem in problems:
        print(problem, file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
